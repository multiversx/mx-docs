#!/usr/bin/env node
/*
  generate-cookbook-manifest.js

  Builds the data the Cookbook landing page renders. Instead of hand-listing 69
  recipes in MDX, this scans each recipe's real frontmatter and emits a JSON
  manifest that `docs/sdk-and-tools/sdk-js/cookbook/index.mdx` imports and feeds
  to <CookbookIndex>. Same idea as generate-llms-txt.js (frontmatter is the single
  source of truth); here the output feeds the human-facing index instead of the
  agent surface.

  Section order and the recipe order *within* each section are read from
  sidebars.js — the one curated reading order — so the index and the sidebar can
  never drift. Recipe card fields are read from each page's YAML frontmatter via
  gray-matter, mapped to the exact prop names <RecipeCard> consumes.

  Output: src/data/cookbook-manifest.json (generated by prebuild and prestart).

  Usage: node scripts/generate-cookbook-manifest.js
*/

const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const ROOT = path.join(__dirname, "..");
const DOCS_DIR = path.join(ROOT, "docs");
const OUTPUT_FILE = path.join(ROOT, "src", "data", "cookbook-manifest.json");

const COOKBOOK_CATEGORY_LABEL = "Cookbook (recipes)";
// A real recipe doc id: cookbook/<section>/<slug>. The section index and the
// agent on-ramp live one level up (cookbook/index, cookbook/agents) and are
// intentionally excluded.
const RECIPE_ID_RE = /^sdk-and-tools\/sdk-js\/cookbook\/[^/]+\/[^/]+$/;

// Recursively locate the sidebar category object with the given label.
function findCategory(node, label) {
  if (Array.isArray(node)) {
    for (const child of node) {
      const found = findCategory(child, label);
      if (found) return found;
    }
    return null;
  }
  if (node && typeof node === "object") {
    if (node.type === "category" && node.label === label) return node;
    for (const value of Object.values(node)) {
      const found = findCategory(value, label);
      if (found) return found;
    }
  }
  return null;
}

// Resolve a doc id to its .mdx/.md file on disk.
function resolveDocFile(docId) {
  for (const ext of [".mdx", ".md"]) {
    const candidate = path.join(DOCS_DIR, `${docId}${ext}`);
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

// Map one recipe's frontmatter to the shape <RecipeCard> reads. Field names are
// deliberately the card's camelCase props so index.mdx can pass records straight
// through with no transform.
function recipeRecord(docId, data, source) {
  const sdkVersions =
    data.sdk_versions && typeof data.sdk_versions === "object"
      ? data.sdk_versions
      : undefined;

  const artifact = /```json\s+title=["']package\.json["']/.test(source)
    ? "project"
    : "reference";
  if (data.artifact !== artifact) {
    throw new Error(
      `${docId}: frontmatter artifact=${data.artifact || "<missing>"}, ` +
        `but the page content derives artifact=${artifact}`
    );
  }

  return {
    title: data.title || docId,
    description: data.description || "",
    href: `/${docId}`,
    difficulty: data.difficulty || undefined,
    artifact,
    tags: Array.isArray(data.tags) ? data.tags : [],
    sdkVersions,
  };
}

function main() {
  const sidebars = require(path.join(ROOT, "sidebars.js"));
  const category = findCategory(sidebars, COOKBOOK_CATEGORY_LABEL);
  if (!category || !Array.isArray(category.items)) {
    console.error(
      `Could not find the "${COOKBOOK_CATEGORY_LABEL}" category in sidebars.js.`
    );
    process.exit(1);
  }

  const sections = [];
  let total = 0;

  for (const item of category.items) {
    // Only the section sub-categories carry recipes; string children (the agent
    // on-ramp) and the category link (the index) are skipped by construction.
    if (!item || item.type !== "category" || !Array.isArray(item.items)) {
      continue;
    }

    const recipeIds = item.items.filter(
      (it) => typeof it === "string" && RECIPE_ID_RE.test(it)
    );
    if (recipeIds.length === 0) continue;

    const recipes = [];
    for (const docId of recipeIds) {
      const file = resolveDocFile(docId);
      if (!file) {
        console.error(`  ! missing file for recipe id: ${docId}`);
        process.exit(1);
      }
      const source = fs.readFileSync(file, "utf8");
      const { data } = matter(source);
      recipes.push(recipeRecord(docId, data, source));
    }

    // Anchor id for in-page section links: the shared <section> folder segment
    // of sdk-and-tools/sdk-js/cookbook/<section>/<slug>.
    const sectionId = recipeIds[0].split("/")[3];

    sections.push({ id: sectionId, label: item.label, recipes });
    total += recipes.length;
  }

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, `${JSON.stringify(sections, null, 2)}\n`, "utf8");

  console.log(`Wrote ${path.relative(ROOT, OUTPUT_FILE)}`);
  console.log(`  ${sections.length} sections, ${total} recipes:`);
  for (const s of sections) {
    console.log(`    ${String(s.recipes.length).padStart(2)}  ${s.label}`);
  }
}

main();
